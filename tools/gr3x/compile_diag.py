"""Compile the date-imprint module's diagnostic form for GR III test builds.

tools/datestamp/datestamp.c with -DDIAG -DSTRICT_PLANES: like GR IV's diagnostic build, but it
only touches picture planes above 0x5d000000 (above GR III's RTOS data and heaps) whose CbCr plane
has the rows it draws. Position independent (checked by linking at two addresses, as gen.py).
Writes core/src/fw/gr3x/datestamp-diag.ts. GR IV's datestamp-code.ts is not regenerated.
"""
import base64,hashlib,sys,tempfile
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/'datestamp'))
import gen
def main():
    cc,ld,objcopy=gen.tools()
    with tempfile.TemporaryDirectory() as t:
        tmp=Path(t)
        a=gen.build(cc,ld,objcopy,tmp,0x10000,['-DDIAG','-DSTRICT_PLANES'])
        b=gen.build(cc,ld,objcopy,tmp,0x543f0000,['-DDIAG','-DSTRICT_PLANES'])
    if a!=b:sys.exit('module is not position independent')
    while len(a)%4:a+=b'\0'
    out=gen.ROOT/'core'/'src'/'fw'/'gr3x'/'datestamp-diag.ts'
    out.write_text('// SPDX-License-Identifier: GPL-2.0-only\n'
        '// GENERATED by tools/gr3x/compile_diag.py from tools/datestamp/datestamp.c (-DDIAG -DSTRICT_PLANES).\n'
        f'// Compiler: {gen.run(cc+["--version"]).splitlines()[0]}\n'
        f'// Source SHA-256: {hashlib.sha256(gen.SRC.read_bytes()).hexdigest()}\n'
        "/** GR III test builds: the date imprint's diagnostic module, planes above 0x5d000000 only. */\n"
        f"export const GR3X_DATESTAMP_DIAG_CODE = '{base64.b64encode(a).decode()}';\n")
    print(len(a))
main()
