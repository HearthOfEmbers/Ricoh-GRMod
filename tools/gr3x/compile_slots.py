"""Compile native/slots.c to a position-independent A32 blob using local clang and ld.lld.

The module is linked twice, at two different addresses; the two images must be byte-identical,
so the blob needs no relocation at all. Firmware functions are absolute addresses in the source.
Only .text/.rodata are allowed. No host executable produced here is run.
"""
import hashlib
import json
import subprocess
import tempfile
from pathlib import Path

REPO=Path(__file__).resolve().parents[2]
source=Path(__file__).with_name('native')/'slots.c'
EXPORTS=('sp_style','sp_after_load','sp_after_save')
flags=['-target','armv7-none-eabi','-mcpu=cortex-a9','-marm','-mfloat-abi=soft','-Os','-fropi',
       '-fno-jump-tables','-ffreestanding','-fno-builtin','-fno-unwind-tables','-fno-asynchronous-unwind-tables',
       '-fno-stack-protector','-c']

def link(obj,folder,base):
    script=Path(folder)/f'link-{base:x}.ld'
    script.write_text('SECTIONS { . = 0x%x; .text : { *(.text .text.*) *(.rodata .rodata.*) } '
                      '/DISCARD/ : { *(.ARM.exidx*) *(.comment) *(.note*) *(.ARM.attributes) } }\n'%base)
    elf=Path(folder)/f'slots-{base:x}.elf';blob=Path(folder)/f'slots-{base:x}.bin'
    subprocess.run(['/usr/bin/ld.lld','-T',str(script),'--no-undefined','-e','0',str(obj),'-o',str(elf)],check=True)
    sections=subprocess.run(['/usr/bin/llvm-objdump','-h',str(elf)],check=True,capture_output=True,text=True).stdout
    allocated=[l.split()[1] for l in sections.splitlines() if l.strip()[:1].isdigit() and l.split()[0]!='0']
    assert set(allocated)<={'.text','.symtab','.shstrtab','.strtab'},allocated
    subprocess.run(['/usr/bin/llvm-objcopy','-O','binary','--only-section=.text',str(elf),str(blob)],check=True)
    nm=subprocess.run(['/usr/bin/llvm-nm','--defined-only',str(elf)],check=True,capture_output=True,text=True).stdout
    symbols={}
    for line in nm.splitlines():
        value,kind,name=line.split()
        if name in EXPORTS:
            assert kind=='T',line;symbols[name]=int(value,16)-base
    assert set(symbols)==set(EXPORTS),symbols
    return blob.read_bytes(),symbols

with tempfile.TemporaryDirectory(prefix='gr3x-slots-') as folder:
    obj=Path(folder)/'slots.o'
    subprocess.run(['/usr/bin/clang',*flags,str(source),'-o',str(obj)],check=True)
    low,exports=link(obj,folder,0x10000000)
    high,again=link(obj,folder,0x20004000)
assert low==high and exports==again,'module is not position independent'
assert len(low)%4==0 and all(v%4==0 for v in exports.values())
result=dict(sourceSha256=hashlib.sha256(source.read_bytes()).hexdigest(),code=low.hex(),exports=exports)
out=REPO/'core/src/fw/gr3x/slots-native.ts'
out.write_text('// SPDX-License-Identifier: GPL-2.0-only\n// Generated by tools/gr3x/compile_slots.py from native/slots.c.\n'
               'export const GR3X_SLOTS_NATIVE = '+json.dumps(result,indent=2)+' as const;\n')
print(json.dumps(dict(bytes=len(low),exports=exports,source_sha256=result['sourceSha256'])))
